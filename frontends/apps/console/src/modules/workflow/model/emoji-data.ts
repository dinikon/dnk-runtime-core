function codePointRange(start: number, end: number) {
  return Array.from({ length: end - start + 1 }, (_, index) => start + index);
}

function unique(values: string[]) {
  return [...new Set(values)];
}

function codePointsToEmoji(codePoints: number[]) {
  return codePoints
    .map((codePoint) => {
      const value = String.fromCodePoint(codePoint);

      if (!emojiPresentation.test(value) && !extendedPictographic.test(value)) {
        return null;
      }

      return emojiPresentation.test(value) ? value : `${value}\uFE0F`;
    })
    .filter((value): value is string => value !== null);
}

function skinToneVariants(values: string[]) {
  return values.flatMap((value) => {
    const base = value.replace("\uFE0F", "");
    return skinTones.map((tone) => `${base}${tone}`);
  });
}

function flagEmoji(countryCode: string) {
  return countryCode
    .toUpperCase()
    .split("")
    .map((letter) => String.fromCodePoint(0x1f1e6 + letter.charCodeAt(0) - 65))
    .join("");
}

